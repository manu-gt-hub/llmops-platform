/**
 * build-corpus.ts — Turns the platform's own documentation (doc/) into the
 * copilot's knowledge base, src/corpus.ts. A Worker cannot read files, so the
 * docs are bundled as a module; a test fails if it is out of date.
 *
 *   npm run corpus
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const DOC = new URL("../doc/", import.meta.url);
const OUT = new URL("../src/corpus.ts", import.meta.url);

/** Document name -> markdown without diagrams (they are noise to the model). */
export function buildCorpus(): Record<string, string> {
  const files: [string, URL][] = [
    ["architecture", new URL("architecture.md", DOC)],
    ["runbook", new URL("runbook.md", DOC)],
    ...readdirSync(new URL("adr/", DOC))
      .filter((f) => /^\d{4}-.*\.md$/.test(f))
      .sort()
      .map((f): [string, URL] => [`adr-${f.slice(0, 4)}`, new URL(`adr/${f}`, DOC)]),
  ];
  return Object.fromEntries(files.map(([name, url]) => [
    name,
    readFileSync(url, "utf-8").replace(/\r\n/g, "\n").replace(/```mermaid[\s\S]*?```\n?/g, "").trim(),
  ]));
}

export function renderCorpus(): string {
  return `/**
 * corpus.ts — GENERATED by scripts/build-corpus.ts from doc/ (npm run corpus).
 * Do not edit: change the docs and regenerate. The copilot's knowledge base.
 */

export const CORPUS: Record<string, string> = ${JSON.stringify(buildCorpus(), null, 2)};
`;
}

if (process.argv[1]?.endsWith("build-corpus.ts")) {
  writeFileSync(OUT, renderCorpus());
  console.log(`wrote src/corpus.ts (${Object.keys(buildCorpus()).join(", ")})`);
}
